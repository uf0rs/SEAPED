"""SEAPED internationalization (English / Russian).

Usage:
    from seaped.i18n import tr, set_language
    set_language("ru")
    tr("nav.dashboard")

Missing keys fall back to English and finally to the key itself, so a typo can
never crash the UI.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict

# NOTE: project_dir is imported lazily so seaped.core may use tr() without
# creating an import cycle.

SETTINGS_FILE = "settings.json"
LANGUAGES: Dict[str, str] = {"ru": "Русский", "en": "English"}
DEFAULT_LANGUAGE = "ru"

_state = {"lang": DEFAULT_LANGUAGE}


def get_language() -> str:
    return _state["lang"]


def set_language(lang: str) -> None:
    _state["lang"] = lang if lang in LANGUAGES else DEFAULT_LANGUAGE


def tr(key: str, **fmt) -> str:
    table = STRINGS.get(_state["lang"]) or STRINGS["en"]
    text = table.get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if fmt:
        try:
            return text.format(**fmt)
        except Exception:
            return text
    return text


# ------------------------------ settings ------------------------------ #

def settings_path() -> Path:
    from .core.config import project_dir

    return project_dir() / SETTINGS_FILE


def load_settings() -> dict:
    path = settings_path()
    if path.exists():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                return data
        except Exception:
            pass
    return {}


def save_setting(key: str, value) -> None:
    data = load_settings()
    data[key] = value
    try:
        settings_path().write_text(
            json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8"
        )
    except OSError:
        pass


def ensure_language(ask: bool = True) -> str:
    """Return the configured language, asking the user on first run."""
    lang = load_settings().get("lang")
    if lang in LANGUAGES:
        set_language(lang)
        return get_language()
    if not ask:
        set_language(DEFAULT_LANGUAGE)
        return get_language()
    from .ui.langpick import ask_language  # deferred: needs textual

    chosen = ask_language() or DEFAULT_LANGUAGE
    set_language(chosen)
    save_setting("lang", chosen)
    return chosen


